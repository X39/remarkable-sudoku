"""Train the small MNIST digit classifier embedded in ui/digit-model.js.

IMPORTANT: everything here is WHITE-ON-BLACK (ink = 1.0, paper = 0.0), the MNIST
convention. The app draws black ink on white paper; digit-recognizer.js inverts
before preprocessing. The preprocessing below must stay identical to
digit-recognizer.js (bounding box, longer side -> 20 px with exact box-filter
area resampling, centre of mass moved to pixel (14,14) of a 28x28 canvas,
integer shift, clipped to the frame).

Usage: python tools/train_digit.py [hidden=64]
Needs numpy + scikit-learn. Data: build/data/mnist.npz (downloaded once).
"""
import datetime
import math
import os
import sys
import urllib.request

import numpy as np
from sklearn.neural_network import MLPClassifier

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "build", "data", "mnist.npz")
OUT = os.path.join(ROOT, "ui", "digit-model.js")
URL = "https://storage.googleapis.com/tensorflow/tf-keras-datasets/mnist.npz"
THRESH = 0.1


def rnd(x):
    return int(math.floor(x + 0.5))


def resize_matrix(src, dst):
    """dst x src matrix of exact box-filter coverage weights."""
    r = src / dst
    m = np.zeros((dst, src))
    for i in range(dst):
        a, b = i * r, (i + 1) * r
        for j in range(int(math.floor(a)), min(src, int(math.ceil(b)))):
            m[i, j] = (min(b, j + 1) - max(a, j)) / r
    return m


def preprocess(img):
    """img: HxW float 0..1, white ink on black. Returns 28x28 float32."""
    img = np.asarray(img, dtype=np.float64)
    out = np.zeros((28, 28))
    ys, xs = np.nonzero(img > THRESH)
    if len(ys) == 0:
        return out.astype(np.float32)
    crop = img[ys.min():ys.max() + 1, xs.min():xs.max() + 1]
    h, w = crop.shape
    s = 20.0 / max(h, w)
    nh, nw = max(1, rnd(h * s)), max(1, rnd(w * s))
    small = resize_matrix(h, nh) @ crop @ resize_matrix(w, nw).T
    oy, ox = (28 - nh) // 2, (28 - nw) // 2
    out[oy:oy + nh, ox:ox + nw] = small
    tot = out.sum()
    if tot <= 0:
        return out.astype(np.float32)
    cy = (out.sum(axis=1) * np.arange(28)).sum() / tot
    cx = (out.sum(axis=0) * np.arange(28)).sum() / tot
    sy, sx = rnd(14 - cy), rnd(14 - cx)
    res = np.zeros((28, 28))
    for y in range(28):
        ty = y + sy
        if 0 <= ty < 28:
            for x in range(28):
                tx = x + sx
                if 0 <= tx < 28:
                    res[ty, tx] = out[y, x]
    return res.astype(np.float32)


def dilate(imgs):
    d = imgs.copy()
    d[:, 1:, :] = np.maximum(d[:, 1:, :], imgs[:, :-1, :])
    d[:, :-1, :] = np.maximum(d[:, :-1, :], imgs[:, 1:, :])
    d[:, :, 1:] = np.maximum(d[:, :, 1:], imgs[:, :, :-1])
    d[:, :, :-1] = np.maximum(d[:, :, :-1], imgs[:, :, 1:])
    return d


def forward(X, W1, b1, W2, b2):
    h = np.maximum(X @ W1 + b1, 0)
    z = h @ W2 + b2
    z -= z.max(axis=1, keepdims=True)
    e = np.exp(z)
    return e / e.sum(axis=1, keepdims=True)


def acc19(P, y):
    m = y >= 1
    return float((P[m][:, 1:].argmax(axis=1) + 1 == y[m]).mean())


def fmt(a):
    return "[" + ",".join(("%.3f" % v).replace("-0.000", "0.000") for v in np.ravel(a)) + "]"


def main():
    hidden = int(sys.argv[1]) if len(sys.argv) > 1 else 64
    if not os.path.exists(DATA):
        os.makedirs(os.path.dirname(DATA), exist_ok=True)
        urllib.request.urlretrieve(URL, DATA)
    d = np.load(DATA)
    xtr, ytr, xte, yte = d["x_train"] / 255.0, d["y_train"], d["x_test"] / 255.0, d["y_test"]
    print("preprocessing...")
    ptr = np.stack([preprocess(i) for i in xtr])
    pte = np.stack([preprocess(i) for i in xte])
    # Augment with dilated (thicker) copies: pen ink is thicker than MNIST strokes.
    Xtr = np.concatenate([ptr, dilate(ptr)]).reshape(-1, 784)
    Ytr = np.concatenate([ytr, ytr])
    clf = MLPClassifier(hidden_layer_sizes=(hidden,), activation="relu", solver="adam",
                        batch_size=256, max_iter=30, early_stopping=False, random_state=1,
                        alpha=1e-4, verbose=False)
    clf.fit(Xtr, Ytr)
    W1, W2 = clf.coefs_
    b1, b2 = clf.intercepts_
    r = [np.round(a, 3) for a in (W1, b1, W2, b2)]
    raw28 = xte.reshape(-1, 784)
    pp = pte.reshape(-1, 784)
    a_raw = acc19(forward(raw28, W1, b1, W2, b2), yte)
    a_pre = acc19(forward(pp, *r), yte)
    a_pre_f = acc19(forward(pp, W1, b1, W2, b2), yte)
    print("test acc 1-9, raw 28x28 (no preprocessing):      %.4f" % a_raw)
    print("test acc 1-9, preprocessed, float weights:       %.4f" % a_pre_f)
    print("test acc 1-9, preprocessed, 3-decimal weights:   %.4f" % a_pre)
    body = "// GENERATED by tools/train_digit.py - do not edit.\n"
    body += "// Model: 784 -> %d (ReLU) -> 10 (softmax), trained on white-on-black MNIST, preprocessed.\n" % hidden
    body += "// Test accuracy (classes 1-9, MNIST test set, preprocessed, 3-decimal weights): %.2f%%\n" % (a_pre * 100)
    body += "// Training date: %s\n" % datetime.date.today().isoformat()
    body += "// W1 is row-major [784][%d], W2 row-major [%d][10].\n" % (hidden, hidden)
    body += ".pragma library\n"
    body += "var DigitModel = {hidden: %d, accuracy19: %.4f,\n" % (hidden, a_pre)
    body += "W1: %s,\nb1: %s,\nW2: %s,\nb2: %s};\n" % tuple(fmt(a) for a in r)
    with open(OUT, "w", newline="\n") as f:
        f.write(body)
    print("wrote %s (%d bytes)" % (OUT, len(body)))
    np.save(os.path.join(ROOT, "build", "data", "preprocessed_test.npy"), pte)
    print("py acc19=%.4f" % a_pre)


if __name__ == "__main__":
    main()
